"""SPEC-0014 requirements 18-21: deterministic bound-tightening LP variants.

A variant differs from its base model only in variable bounds. Each variant is
generated by tightening bounds toward the instance's frozen witness so the
witness remains feasible: for every changed variable with original bounds
(lo, hi) and witness value w the new bounds satisfy lo <= lo' <= w <= hi' <= hi,
with strict movement on every side that has room — lo < lo' < w when lo < w,
w < hi' < hi when w < hi, and a finite w - q / w + q when the original side is
infinite. A bound already equal to the witness cannot move without excluding
it; that side stays at the witness and brackets it at equality.

The generator is the instance generator's SHA-256 counter PRNG
(lp_generate.Random) over a recorded seed band: the caller passes
seed = variant_seed_base + the instance's index in the merged development plus
extension manifest order, and the benchmark tool computes it. Every movement
is a dyadic fraction k/2**m with m in 1..=8 and k in 1..2**m-1 drawn from the
PRNG, so variant bounds are exact in both FP64 and FP32. Exactly
min(n_variables, changes) distinct variables change, the same set for every
variant of the family, and variant k never depends on the requested count, so
a size-N batch's variants are the first N of any larger batch of the same
instance and seed (the prefix property, requirement 20). A variant batch is
refused for an instance without a frozen witness (requirement 21).

CLI: python3 tools/lp_variants.py INSTANCE-ID --count N --seed S [--check] [--out FILE]
emits the lp-batch-request-v1 variant document; --check instead re-derives the
family at the frozen throughput protocol's seed band and grid sizes and
verifies every variant with exact Fraction arithmetic.
"""
import argparse
import struct
from fractions import Fraction as F
from lp_generate import Random
from lp_protocol import ROOT, checked_reference, encoded, read_json, write_json
from validate_artifacts import validator

MANIFESTS = ['benchmarks/manifests/lp-development-v1.json',
             'benchmarks/manifests/lp-development-extension-v1.json']
PROTOCOL = ROOT / 'benchmarks/configs/lp-throughput-v1.json'


def merged_instances():
    """Development then extension instance entries, in merged manifest order."""
    return [instance for manifest in MANIFESTS for instance in read_json(ROOT / manifest)['instances']]


def instance_entry(instance_id):
    for instance in merged_instances():
        if instance['id'] == instance_id:
            return instance
    raise ValueError('unknown instance: ' + instance_id)


def bound(value, sign):
    """Exact Fraction of a finite model bound, or None for the infinite side."""
    kind = value['kind']
    if kind == 'finite':
        return F.from_float(value['value'])
    if kind == ('positive_infinity' if sign > 0 else 'negative_infinity'):
        return None
    raise ValueError('malformed variable bound')


def fraction(rng):
    """One dyadic movement k/2**m in (0, 1): m in 1..=8, k in 1..2**m-1."""
    m = 1 + rng.integer(8)
    return F(1 + rng.integer((1 << m) - 1), 1 << m)


def exact(value):
    """The float of an exact Fraction, refused unless exact in FP64 and FP32."""
    result = float(value)
    if F.from_float(result) != value or struct.unpack('>f', struct.pack('>f', result))[0] != result:
        raise ValueError('variant bound is not exact in FP64 and FP32')
    return result


def tightened(lo, hi, w, q_lo, q_hi):
    """The tightened (lower, upper) pair for one changed variable.

    Each side moves toward the witness by a dyadic fraction of its distance to
    the witness and stays inside the original bounds; a side already at the
    witness stays, and an infinite side becomes finite at w -/+ q.
    """
    if lo is not None and not lo <= w:
        raise ValueError('witness below the original lower bound')
    if hi is not None and not w <= hi:
        raise ValueError('witness above the original upper bound')
    if lo is None:
        lower = w - q_lo
    elif lo < w:
        lower = lo + (w - lo) * q_lo
    else:
        lower = lo
    if hi is None:
        upper = w + q_hi
    elif w < hi:
        upper = hi - (hi - w) * q_hi
    else:
        upper = hi
    if not (lo is None or lo <= lower) or not (hi is None or upper <= hi) or not lower <= w <= upper:
        raise ValueError('tightened bounds violate the variant contract')
    return exact(lower), exact(upper)


def variants(instance_model, witness, seed, count, changes):
    """The first `count` variants of one instance's family, in solve order.

    Deterministic in (instance_model, witness, seed, changes) and independent
    of `count` beyond truncation: variants(m, w, s, N, c) == variants(m, w, s,
    M, c)[:N] for N < M (requirement 20).
    """
    if witness is None:
        raise ValueError('a variant batch requires a frozen witness')
    if count < 1 or changes < 1:
        raise ValueError('variant count/changes must be positive')
    rng = Random(seed)
    variables = instance_model['variables']
    values = {v['variable_id']: F.from_float(v['value']) for v in witness['candidate']['values']}
    n = len(variables)
    if any(v['id'] not in values for v in variables):
        raise ValueError('witness does not cover every variable')
    order = list(range(n))
    for i in range(min(n, changes)):
        j = i + rng.integer(n - i)
        order[i], order[j] = order[j], order[i]
    changed = sorted(order[:min(n, changes)])
    family = []
    for index in range(count):
        edits = []
        for position in changed:
            variable = variables[position]
            w = values[variable['id']]
            lo = bound(variable['lower'], -1)
            hi = bound(variable['upper'], +1)
            lower, upper = tightened(lo, hi, w, fraction(rng), fraction(rng))
            edits.append(dict(variable_id=variable['id'], lower=lower, upper=upper))
        family.append(dict(index=index, changes=edits))
    return family


def request(instance_id, kind, solves, variants_list, seed, changes, batch_time_limit_ms):
    """One validated lp-batch-request-v1 document for `solves` ordered solves.

    A repeat batch carries an empty variant list and a null generator; a
    variant batch carries exactly `solves` variants indexed 0..solves-1 and its
    generator record. The instance id names the model the batch binds to; it
    is not part of the document.
    """
    if not solves >= 1 or not batch_time_limit_ms >= 1:
        raise ValueError('batch solves/limit must be positive: ' + instance_id)
    if kind == 'repeat':
        if variants_list or seed is not None or changes is not None:
            raise ValueError('a repeat batch carries no variants or generator: ' + instance_id)
        generator = None
    elif kind == 'variant':
        if seed is None or changes is None or changes < 1:
            raise ValueError('a variant batch requires its generator record: ' + instance_id)
        if len(variants_list) != solves or any(v['index'] != position for position, v in enumerate(variants_list)):
            raise ValueError('variant batch count/order: ' + instance_id)
        for variant in variants_list:
            ids = [c['variable_id'] for c in variant['changes']]
            if not ids or len(set(ids)) != len(ids) or any(c['lower'] > c['upper'] for c in variant['changes']):
                raise ValueError('invalid variant bound change: ' + instance_id)
        generator = dict(seed=seed, changes=changes)
    else:
        raise ValueError('unknown batch kind: ' + str(kind))
    value = dict(schema_version=1, kind=kind, solves=solves, variants=variants_list,
                 generator=generator, batch_time_limit_ms=batch_time_limit_ms)
    validator('lp-batch-request-v1.schema.json').validate(value)
    return value


def dyadic(q):
    """(k, m) when q is a dyadic fraction k/2**m in (0, 1) with m in 1..=8."""
    if not 0 < q < 1:
        return None
    if q.denominator & (q.denominator - 1):
        return None
    m = q.denominator.bit_length() - 1
    return (q.numerator, m) if 1 <= m <= 8 else None


def check_change(variable, w, change):
    """Exact-Fraction verification of one change against the variant contract."""
    lo = bound(variable['lower'], -1)
    hi = bound(variable['upper'], +1)
    lower = F.from_float(change['lower'])
    upper = F.from_float(change['upper'])
    assert lo is None or lo <= lower, 'lower bound moved outside the original bounds'
    assert hi is None or upper <= hi, 'upper bound moved outside the original bounds'
    assert lower <= w <= upper, 'variant no longer brackets the witness'
    if lo is None:
        assert dyadic(w - lower), 'non-dyadic lower movement from an infinite bound'
    elif lo < w:
        assert lo < lower < w and dyadic((lower - lo) / (w - lo)), 'lower bound did not move strictly toward the witness'
    else:
        assert lower == w == lo, 'a bound at the witness cannot move'
    if hi is None:
        assert dyadic(upper - w), 'non-dyadic upper movement from an infinite bound'
    elif w < hi:
        assert w < upper < hi and dyadic((hi - upper) / (hi - w)), 'upper bound did not move strictly toward the witness'
    else:
        assert upper == w == hi, 'a bound at the witness cannot move'


def check(instance_id):
    """Re-derive one witness instance's family at the frozen protocol's seed
    band and grid sizes and assert the contract for every variant and change.

    Raises ValueError for an unknown or witness-less instance and
    AssertionError for any violated variant invariant.
    """
    entry = instance_entry(instance_id)
    if entry['witness'] is None:
        raise ValueError('a variant batch requires a frozen witness: ' + instance_id)
    value = read_json(PROTOCOL)
    instances = merged_instances()
    seed = value['variant_seed_base'] + next(p for p, i in enumerate(instances) if i['id'] == instance_id)
    count = max(max(block['sizes']) if 'sizes' in block else max(block['variants']) + 1
                for block in value['blocks'] if block['kind'] in ('batch-variant', 'batch-variant-short', 'fresh-variant'))
    model = read_json(checked_reference(ROOT, entry['model']))
    witness = read_json(checked_reference(ROOT, entry['witness']))
    values = {v['variable_id']: F.from_float(v['value']) for v in witness['candidate']['values']}
    family = variants(model, witness, seed, count, value['variant_changes'])
    by_id = {v['id']: v for v in model['variables']}
    assert len(family) == count
    for variant in family:
        assert len(variant['changes']) == min(len(model['variables']), value['variant_changes'])
        for change in variant['changes']:
            check_change(by_id[change['variable_id']], values[change['variable_id']], change)
    print(instance_id, 'checked', count, 'variants x', len(family[0]['changes']), 'changes')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('instance')
    parser.add_argument('--count', type=int, default=1)
    parser.add_argument('--seed', type=int, default=None,
                        help='variant_seed_base plus the instance index in the merged manifest order')
    parser.add_argument('--changes', type=int, default=256)
    parser.add_argument('--batch-time-limit-ms', type=int, default=60000)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--out', type=str, default=None)
    args = parser.parse_args()
    if args.check:
        check(args.instance)
        return
    if args.seed is None:
        raise SystemExit('--seed is required: variant_seed_base plus the instance index')
    entry = instance_entry(args.instance)
    if entry['witness'] is None:
        raise SystemExit('a variant batch requires a frozen witness: ' + args.instance)
    model = read_json(checked_reference(ROOT, entry['model']))
    witness = read_json(checked_reference(ROOT, entry['witness']))
    family = variants(model, witness, args.seed, args.count, args.changes)
    document = request(args.instance, 'variant', args.count, family, args.seed, args.changes, args.batch_time_limit_ms)
    if args.out:
        write_json(args.out, document)
    else:
        print(encoded(document).decode(), end='')


if __name__ == '__main__':
    main()
