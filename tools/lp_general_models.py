"""Independent development LPs with active inequalities and bound complementarity.

Construction witnesses generate data only; solver inputs never include answers.
No holdout is generated by this development command.
"""
import argparse
import random
from lp_general_common import BASE, put, ref

FAMILIES = ('irregular', 'rectangular', 'dense_blocks', 'ill_scaled', 'degenerate', 'dense')


def generate(family, size, seed):
    if family not in FAMILIES or size < 4:
        raise ValueError('model descriptor')
    rng = random.Random(seed)
    n = size
    m = max(3, n // 2) if family in ('rectangular', 'dense') else n + n // 3
    x = [rng.choice([0., .25, .5, 1.]) for _ in range(n)]
    rows = []
    dual = []
    for i in range(m):
        if family == 'dense':
            indices = list(range(n))
        elif family == 'dense_blocks':
            start = 16 * ((i // 16) % ((n + 15) // 16))
            indices = sorted(set(range(start, min(n, start + 16))) | {rng.randrange(n)})
        else:
            indices = sorted(rng.sample(range(n), min(n, rng.randrange(2, 12))))
        scale = 2. ** ((i % 13 - 6) * 2) if family == 'ill_scaled' else 1.
        terms = [(j, rng.choice([-15,-11,-7,-3,1,5,9,13]) / 16. * scale) for j in indices]
        if family == 'degenerate' and i % 3 == 2:
            terms = rows[-1]['terms'][:]
        activity = sum(a * x[j] for j, a in terms)
        side = i % 4
        multiplier = (rng.randrange(1, 8) / 8.) / scale
        if side == 0:
            lower, upper, y = activity, activity + 2. * scale, multiplier
        elif side == 1:
            lower, upper, y = activity - 2. * scale, activity, -multiplier
        elif side == 2:
            lower, upper, y = None, activity + scale, 0.
        else:
            lower, upper, y = activity - scale, None, 0.
        rows.append(dict(terms=terms, lower=lower, upper=upper))
        dual.append(y)
    objective = [0.] * n
    for row, y in zip(rows, dual):
        for j, a in row['terms']:
            objective[j] += a * y
    for j, v in enumerate(x):
        r = rng.randrange(1, 8) / 8.
        objective[j] += r if v == 0 else -r if v == 1 else 0.
    bound = lambda v, side: dict(kind='finite', value=v) if v is not None else dict(kind=side+'_infinity')
    identity = f'general-dev-{family}-{size}-{seed}'
    doc = dict(schema_version=1, model_id=identity,
        variables=[dict(id=3*j+7, domain='continuous', lower=bound(0.,''), upper=bound(1.,'')) for j in range(n)],
        constraints=[dict(id=5*i+11, lower=bound(row['lower'],'negative'), upper=bound(row['upper'],'positive'),
            terms=[dict(variable_id=3*j+7, coefficient=a) for j,a in row['terms']]) for i,row in enumerate(rows)],
        objective=dict(sense='minimize', offset=3.25,
            terms=[dict(variable_id=3*j+7, coefficient=c) for j,c in enumerate(objective) if c != 0]))
    return doc, dict(primal=x, dual=dual, rows=m, columns=n,
        nonzeros=sum(len(r['terms']) for r in rows), family=family, seed=seed,
        partition='development', license='MIT', source='repository generator')


def materialize():
    directory = BASE/'models-development-v1'
    directory.mkdir(exist_ok=False, parents=True)
    entries = []
    for family in FAMILIES:
        sizes = [33,129,257] if family == 'dense' else [33,257,4097]
        for size in sizes:
            for repeat in range(4):
                seed = 790000 + 10000*FAMILIES.index(family) + size*4 + repeat
                doc, witness = generate(family,size,seed)
                model = put(directory/(doc['model_id']+'.json'),doc)
                construction = put(directory/(doc['model_id']+'.construction.json'),witness)
                entries.append(dict(model=model,construction=construction,
                    family=family,size=size,seed=seed,partition='development'))
    put(directory/'manifest.json',dict(schema_version=1,generator=ref(__file__),models=entries,
        holdout_accessed=False,scientific_confirmation=False))


if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('command',choices=['development'])
    parser.parse_args(); materialize()
